import { test, expect, Page } from "@playwright/test";
import { readFileSync } from "node:fs";
const password = process.env.DEMO_PASSWORD;
if (!password) throw new Error("Local demo credential required");
const fixtures = JSON.parse(readFileSync("../artifacts/release-browser-fixtures.json", "utf8"));
const headers = { Origin: "http://localhost:3000" };
async function login(page: Page, email: string) {
  await page.goto("/login");
  await page.getByLabel("Email", { exact: true }).fill(email);
  await page.getByLabel("Password", { exact: true }).fill(password!);
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Workspace overview" })).toBeVisible();
}
test("complete independent approval, durable execution and auditor trace", async ({ page, browser }, info) => {
  const fixture = fixtures[info.project.name];
  await login(page, "operator.1@example.com");
  const before = await (await page.request.get(`/api/v1/accounts/${fixture.account_id}`)).json();
  expect(before.status).toBe("blocked");
  await page.goto("/investigations");
  await page.getByLabel("Customer", { exact: true }).selectOption(fixture.customer_id);
  await page.getByLabel("Investigation goal", { exact: true }).fill("Investigate resolved billing and eligibility for safe synthetic reactivation");
  const investigationResponse = page.waitForResponse(r => r.url().endsWith("/api/v1/investigations") && r.request().method() === "POST");
  await page.getByRole("button", { name: "Run read-only investigation" }).click();
  const response = await investigationResponse;
  expect(response.ok()).toBe(true);
  const investigation = await response.json();
  const result = page.getByRole("region", { name: "Investigation result" });
  await expect(result.getByRole("heading", { name: "Verified retrieval evidence" })).toBeVisible();
  await expect(result.getByRole("region", { name: "Planner execution trace" })).toBeVisible();
  await expect(result.getByRole("heading", { name: "Evidence reconciliation", exact: true })).toBeVisible();
  const references = investigation.evidence.flatMap((e: { sources: {source_type: string; evidence_id: string}[] }) => e.sources).filter((s: {source_type: string}) => ["account", "transaction", "policy"].includes(s.source_type)).map((s: {evidence_id: string}) => s.evidence_id);
  await page.goto("/action-proposals");
  await page.getByLabel("Investigation ID", { exact: true }).fill(investigation.investigation_id);
  await page.getByRole("combobox", { name: "Action", exact: true }).selectOption("reactivate_account");
  await page.getByLabel("Target resource ID", { exact: true }).fill(fixture.account_id);
  await page.getByLabel("Evidence IDs, separated by commas", { exact: true }).fill(references.join(","));
  const evaluationResponse = page.waitForResponse(r => r.url().endsWith("/api/v1/action-proposals") && r.request().method() === "POST");
  await page.getByRole("button", { name: "Evaluate eligibility" }).click();
  const evaluation = await (await evaluationResponse).json();
  expect(evaluation.receipt.decision).toBe("REQUIRE_APPROVAL");
  await page.getByRole("button", { name: "Request independent approval" }).click();
  const approvalLink = page.getByRole("link", { name: "Approval: PENDING" });
  await expect(approvalLink).toBeVisible();
  const approvalPath = await approvalLink.getAttribute("href");
  const approvalId = approvalPath!.split("/").pop()!;
  await approvalLink.click();
  await expect(page.getByRole("button", { name: "Approve action", exact: true })).toHaveCount(0);
  expect((await page.request.post(`/api/v1/approvals/${approvalId}/approve`, { headers, data: { reason: "Self approval must fail" } })).status()).toBe(403);
  const reviewer = await browser.newContext({ viewport: page.viewportSize()! });
  const auditor = await browser.newContext({ viewport: page.viewportSize()! });
  const foreign = await browser.newContext({ viewport: page.viewportSize()! });
  try {
    const reviewPage = await reviewer.newPage();
    await login(reviewPage, "reviewer.1@example.com");
    await reviewPage.goto("/approvals");
    await expect(reviewPage.getByRole("heading", { name: "Approval queue" })).toBeVisible();
    await reviewPage.goto(approvalPath!);
    await expect(reviewPage.getByRole("heading", { name: "Supporting evidence" })).toBeVisible();
    await reviewPage.getByLabel("Review reason").fill("Independent fictional release evidence and deterministic policy reviewed");
    await reviewPage.getByRole("button", { name: "Approve action", exact: true }).click();
    await expect(reviewPage.getByRole("heading", { name: "APPROVED", exact: true })).toBeVisible();
    await page.goto("/execution-jobs");
    await page.getByLabel("Proposal ID", { exact: true }).fill(evaluation.proposal.proposal_id);
    await page.getByLabel("Decision ID", { exact: true }).fill(evaluation.receipt.decision_id);
    await page.getByLabel("Approval ID (when required)", { exact: true }).fill(approvalId);
    const submitted = page.waitForResponse(r => r.url().endsWith("/api/v1/execution-jobs") && r.request().method() === "POST");
    await page.getByRole("button", { name: "Submit durable job" }).click();
    const job = await (await submitted).json();
    let completed = job;
    await expect.poll(async () => {
      const read = await page.request.get(`/api/v1/execution-jobs/${job.id}`);
      expect(read.ok()).toBe(true);
      completed = await read.json();
      return completed.status;
    }, { timeout: 30000, intervals: [100, 250, 500, 1000] }).toBe("COMPLETED");
    await page.getByRole("button", { name: "Refresh jobs", exact: true }).click();
    const ownJob = page.locator("article").filter({ hasText: job.id });
    await expect(ownJob).toHaveCount(1);
    await ownJob.getByRole("button", { name: "reactivate_account · COMPLETED", exact: true }).click();
    await expect(page.getByRole("heading", { name: "Execution: COMMITTED", exact: true })).toBeVisible();
    await expect(page.getByText("Outcome verified: Yes", { exact: true })).toBeVisible();
    const receipt = await (await page.request.get(`/api/v1/action-executions/${completed.receipt_id}`)).json();
    expect(receipt.verified).toBe(true);
    const after = await (await page.request.get(`/api/v1/accounts/${fixture.account_id}`)).json();
    expect(after.status).toBe("active");
    expect(after.evidence_version).toBe(before.evidence_version + 1);
    const replay = await page.request.post("/api/v1/execution-jobs", { headers: {...headers, "Idempotency-Key": `release-duplicate-${crypto.randomUUID()}`}, data: { proposal_id: evaluation.proposal.proposal_id, decision_id: evaluation.receipt.decision_id, approval_id: approvalId } });
    // A different key cannot reuse a consumed grant to commit again.
    expect(replay.status()).toBe(409);
    const identity = await (await page.request.get("/api/v1/auth/me")).json();
    const repeated = await page.request.post("/api/v1/execution-jobs", { headers: {...headers, "Idempotency-Key": `ui-${identity.user_id}-${evaluation.proposal.proposal_id}`}, data: { proposal_id: evaluation.proposal.proposal_id, decision_id: evaluation.receipt.decision_id, approval_id: approvalId } });
    expect(repeated.status()).toBe(200);
    expect((await repeated.json()).id).toBe(job.id);
    expect(await (await page.request.get(`/api/v1/accounts/${fixture.account_id}`)).json()).toEqual(after);
    const auditPage = await auditor.newPage();
    await login(auditPage, "auditor.1@example.com");
    await auditPage.goto(`/diagnostics?trace=${job.id}`);
    await auditPage.getByRole("button", { name: "Trace operations", exact: true }).click();
    await expect(auditPage.getByRole("heading", { name: "End-to-end operational timeline" })).toBeVisible();
    await expect(auditPage.getByText("execution_verified", { exact: false }).first()).toBeVisible();
    const foreignPage = await foreign.newPage();
    await login(foreignPage, "admin.0@example.com");
    for (const path of [`/investigations/${investigation.investigation_id}`, `/approvals/${approvalId}`, `/execution-jobs/${job.id}`]) {
      expect((await foreignPage.request.get(`/api/v1${path}`)).status()).toBe(404);
    }
    await foreignPage.goto(`/investigations/${investigation.investigation_id}`);
    await expect(foreignPage.getByRole("alert").filter({ hasText: "Investigation not found" })).toBeVisible();
    await foreignPage.goto(`/action-proposals/approval/${approvalId}`);
    await expect(foreignPage.getByRole("alert").filter({ hasText: "Approval unavailable" })).toBeVisible();
    await foreignPage.goto("/execution-jobs");
    await expect(foreignPage.getByText(/Active jobs:/)).not.toContainText("Loading");
    await expect(foreignPage.getByText(job.id, { exact: true })).toHaveCount(0);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.screenshot({ path: info.outputPath("durable-release.png"), fullPage: true });
  } finally { await reviewer.close(); await auditor.close(); await foreign.close(); }
});

test("security override is deterministically denied with no execution control", async ({ page }) => {
  await login(page, "admin.0@example.com");
  const customers = await (await page.request.get("/api/v1/customers?limit=100")).json();
  const customer = customers.items.find((c: {name: string}) => c.name === "Fictional Client 0-01");
  const accounts = await (await page.request.get("/api/v1/accounts?limit=100")).json();
  const account = accounts.items.find((a: {customer_id: string}) => a.customer_id === customer.id);
  const before = await (await page.request.get(`/api/v1/accounts/${account.id}`)).json();
  await page.goto("/investigations");
  await page.getByLabel("Customer", { exact: true }).selectOption(customer.id);
  await page.getByLabel("Investigation goal", { exact: true }).fill("Read security review evidence without changing state");
  const observed = page.waitForResponse(r => r.url().endsWith("/api/v1/investigations") && r.request().method() === "POST");
  await page.getByRole("button", { name: "Run read-only investigation" }).click();
  const investigation = await (await observed).json();
  const refs = investigation.evidence.flatMap((e: {sources: {source_type: string; evidence_id: string}[]}) => e.sources).filter((s: {source_type: string}) => ["account", "policy"].includes(s.source_type)).map((s: {evidence_id: string}) => s.evidence_id);
  await page.goto("/action-proposals");
  await page.getByLabel("Investigation ID", { exact: true }).fill(investigation.investigation_id);
  await page.getByRole("combobox", { name: "Action", exact: true }).selectOption("override_security_block");
  await page.getByLabel("Target resource ID", { exact: true }).fill(account.id);
  await page.getByLabel("Evidence IDs, separated by commas", { exact: true }).fill(refs.join(","));
  await page.getByRole("button", { name: "Evaluate eligibility" }).click();
  await expect(page.getByRole("heading", { name: "DENIED", exact: true })).toBeVisible();
  await expect(page.getByText(/security_override_prohibited/)).toBeVisible();
  await expect(page.getByRole("button", { name: "Execute synthetic action", exact: true })).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Request independent approval", exact: true })).toHaveCount(0);
  expect(await (await page.request.get(`/api/v1/accounts/${account.id}`)).json()).toEqual(before);
});
